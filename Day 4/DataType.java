public class DataType {
  
  // Data types :
  // data type specify the different sizes and values that can be stored in the variable.

  // There are two types of data types in Java:

  // 1.Primitive data types:
  //      exp : boolean, char, byte, short, int, long, float and double.


  // 2.Non-primitive data types:
  //    exp : Classes, Interfaces, and Arrays.



  public static void main(String[] args) {
    
    System.out.println("Data Type : ");

    // Boolean data type
    Boolean a = true;
    Boolean b = false;

    // byte data type
    byte c = 10;
    byte d = 20;

    // short Data type
    short e = 10000;
    short f = 20000;

    // int data type
    int num2 = 234;

    // long data type
    long log = 34545L;

    // float data type
    float decimal = 345.6565f;

    // double data type
    double dou = 345.765;

    // char data type
    char letter = 'z';
  }
}
